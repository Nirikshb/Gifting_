import { randomUUID } from 'crypto';

export const PRODUCT_IMAGE_EXTENSIONS = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'image/gif': 'gif',
  'image/avif': 'avif',
} as const;

export type ProductImageMimeType = keyof typeof PRODUCT_IMAGE_EXTENSIONS;

export const PRODUCT_IMAGE_ACCEPTED_TYPES = Object.keys(
  PRODUCT_IMAGE_EXTENSIONS,
).join(',');

const STORED_FILE_NAME_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp|gif|avif)$/;

/**
 * The browser supplied content type is never trusted. The type is detected
 * from the file signature instead, so a renamed executable cannot be stored
 * as a product image.
 */
export function detectProductImageMimeType(
  buffer: Buffer,
): ProductImageMimeType | null {
  if (buffer.length >= 8 && isAscii(buffer, 0, 8, '\x89PNG\r\n\x1a\n')) {
    return 'image/png';
  }

  if (buffer.length >= 3 && isAscii(buffer, 0, 3, '\xff\xd8\xff')) {
    return 'image/jpeg';
  }

  if (buffer.length >= 6) {
    const header = buffer.toString('ascii', 0, 6);
    if (header === 'GIF87a' || header === 'GIF89a') {
      return 'image/gif';
    }
  }

  if (buffer.length >= 12 && isAscii(buffer, 0, 4, 'RIFF')) {
    if (isAscii(buffer, 8, 12, 'WEBP')) {
      return 'image/webp';
    }
  }

  if (buffer.length >= 12 && isAscii(buffer, 4, 8, 'ftyp')) {
    const brand = buffer.toString('ascii', 8, 12);
    if (brand === 'avif' || brand === 'avis') {
      return 'image/avif';
    }
  }

  return null;
}

function isAscii(
  buffer: Buffer,
  start: number,
  end: number,
  expected: string,
): boolean {
  if (buffer.length < end) {
    return false;
  }

  return buffer.toString('binary', start, end) === expected;
}

/**
 * Stored names are generated by the server, so an upload can never collide
 * with another file or escape the upload directory.
 */
export function buildProductImageFileName(
  mimeType: ProductImageMimeType,
): string {
  return `${randomUUID()}.${PRODUCT_IMAGE_EXTENSIONS[mimeType]}`;
}

export function isSafeProductImageFileName(value: string): boolean {
  return STORED_FILE_NAME_PATTERN.test(value);
}

/**
 * Content type for a stored file, derived from its extension.
 */
export function productImageMimeTypeFromFileName(value: string): string | null {
  const extension = value.split('.').pop()?.toLowerCase();

  switch (extension) {
    case 'jpg':
      return 'image/jpeg';
    case 'png':
      return 'image/png';
    case 'webp':
      return 'image/webp';
    case 'gif':
      return 'image/gif';
    case 'avif':
      return 'image/avif';
    default:
      return null;
  }
}

/**
 * The admin supplied name is only used for display. Path separators and
 * control characters are removed.
 */
export function sanitizeOriginalFileName(value: string): string {
  const base = value.split(/[\\/]/).pop() ?? 'image';
  const cleaned = Array.from(base)
    .filter((character) => {
      const code = character.charCodeAt(0);
      return code >= 32 && code !== 127;
    })
    .join('')
    .trim();

  if (cleaned === '') {
    return 'image';
  }

  return cleaned.slice(0, 255);
}

/**
 * Images are served through the storefront origin so the browser never needs
 * direct access to the API host.
 */
export function buildProductImageUrl(
  frontendOrigin: string,
  storedName: string,
): string {
  return `${frontendOrigin.replace(/\/$/, '')}/api/product-images/${storedName}`;
}
