import { Transform, Type } from 'class-transformer';
import {
  IsBoolean,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsString,
  Matches,
  Max,
  MaxLength,
  Min,
} from 'class-validator';
import {
  MAX_STOCK_QUANTITY,
  PRODUCT_PRICE_PATTERN,
} from '../utils/product-validation';

export const trimString = ({ value }: { value: unknown }) =>
  typeof value === 'string' ? value.trim() : value;

/**
 * Numbers are accepted for convenience but converted to a fixed two decimal
 * string so no floating point rounding reaches the database.
 */
export const priceToString = ({ value }: { value: unknown }) => {
  if (typeof value === 'number' && Number.isFinite(value)) {
    return value.toFixed(2);
  }

  return typeof value === 'string' ? value.trim() : value;
};

export class CreateProductDto {
  @Transform(trimString)
  @IsString()
  @IsNotEmpty()
  @MaxLength(150)
  name!: string;

  @Transform(trimString)
  @IsString()
  @IsNotEmpty()
  @MaxLength(180)
  slug!: string;

  @Transform(trimString)
  @IsString()
  @IsNotEmpty()
  @MaxLength(5000)
  description!: string;

  @Transform(priceToString)
  @IsString()
  @Matches(PRODUCT_PRICE_PATTERN, {
    message:
      'price must be a positive amount with up to two decimal places (for example 249 or 249.50)',
  })
  price!: string;

  @Transform(trimString)
  @IsString()
  @IsNotEmpty()
  @MaxLength(80)
  category!: string;

  @Type(() => Number)
  @IsInt()
  @Min(0)
  @Max(MAX_STOCK_QUANTITY)
  stockQuantity!: number;

  @IsOptional()
  @IsBoolean()
  isActive?: boolean;

  /**
   * Reference to an image uploaded through the admin area. The file name and
   * the public URL are generated by the server, so a product can only point
   * at an image this studio uploaded.
   */
  @IsOptional()
  @IsInt()
  @Min(1)
  imageId?: number | null;
}
